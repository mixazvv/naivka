// Pure behavior simulations: deterministic clock, randomness and persistence.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const context={window:{},Date,performance:{now:()=>0},Math};vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(__dirname,'../web/pet-mind.js'),'utf8'),context);
const create=context.window.PetMind.create;
let wall=Date.UTC(2026,10,1,12),mono=0,saves=[];
const options={clock:()=>wall,monotonic:()=>mono,random:()=>0,save:v=>saves.push(v)};
const mind=create(options);
assert.equal(mind.nextEvent(),null,'rare events on initial mount');
mind.visit('private.example');mind.visit('tileSpeed');
assert.equal(mind.snapshot().visits['private.example'],undefined);
assert(mind.affinity('tileSpeed')>mind.affinity('tileIp'));
mind.flush();assert.equal(saves.length,0,'writes must be throttled');
mono=60001;wall+=60001;mind.flush();assert.equal(saves.length,1);
mind.flush();assert.equal(saves.length,1,'unchanged memory written twice');
const restored=create({...options,memory:mind.snapshot()});restored.flush(true);assert.equal(saves.length,1,'remount rewrites unchanged preferences');
const energy=mind.state().energy;mind.acted('move');mono+=20000;mind.observe('on');assert(mind.state().energy<energy);
mind.acted('rest');const tired=mind.state().energy;mono+=20000;mind.observe('on');assert(mind.state().energy>tired);
mono+=11*60000;wall+=11*60000;
assert.equal(mind.nextEvent(),'toy');
assert.equal(mind.nextEvent(),null,'event spam');
mind.flush(true);
const restart=create({...options,memory:mind.snapshot()});mono+=11*60000;wall+=11*60000;
assert.equal(restart.nextEvent(),null,'cooldown lost on restart');
const clean=create({...options,memory:{version:99,visits:{'site.secret':999999}}});assert.equal(Object.keys(clean.snapshot().visits).length,0);
const quiet=create(options);quiet.acted('move');const beforePause=quiet.state().energy;quiet.pause(true);mono+=86400000;quiet.observe('on');quiet.pause(false);assert.equal(quiet.state().energy,beforePause,'absence penalizes energy');
console.log('Pet habits, bounded private memory, save throttling, fatigue/recovery and persistent rare-event cooldown: OK');
